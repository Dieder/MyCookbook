export function localizeExpandedRecipe(recipe: Recipe, lang: LanguageCode): Recipe {
  if (lang === 'en') return recipe;
  const bp = BLUEPRINT_MAP.get(recipe.id);
  if (!bp) return recipe;

  const l = lang as NonEnLang;
  const [
    ,
    chapterId,
    title,
    ,
    mainIng,
    ,
    ,
    secondaryIng,
    aromatic,
    finishing,
    region,
    season,
    ,
    ,
    ,
    methodStyle,
  ] = bp;

  const localizedSeason = SEASONS_LOCALE[l][season] ?? recipe.season;
  const unitMap = UNITS_LOCALE[l];
  const baseIngMap = BASE_ING_LOCALE[l];
  const storyT = STORY_TEMPLATES[l];
  const m = METHOD_SPECS[l][methodStyle];

  // Parse plate index number from fig caption or plateNumber ("Plate 7" -> 7)
  const figMatch = recipe.figureCaption.match(/Fig\.\s*(\d+)/i);
  const figNum = figMatch ? Number(figMatch[1]) : 7;

  return {
    ...recipe,
    season: localizedSeason,
    figureCaption: storyT.figPrefix(figNum, title, finishing),
    storyExcerpt: storyT.excerpt(region, title, mainIng, secondaryIng, aromatic, finishing),
    storyParagraphs: [
      storyT.para1(region, title, localizedSeason, mainIng, secondaryIng, aromatic),
      storyT.para2(finishing),
    ],
    pullQuote: storyT.quote(aromatic, finishing),
    pairingNote: PAIRING_BY_CHAPTER[l][chapterId] ?? recipe.pairingNote,
    ingredients: recipe.ingredients.map((ing) => ({
      ...ing,
      name: baseIngMap[ing.name] ?? ing.name,
      metricUnit: unitMap[ing.metricUnit] ?? ing.metricUnit,
      imperialUnit: unitMap[ing.imperialUnit] ?? ing.imperialUnit,
    })),
    techniques: recipe.techniques.map((tech) => ({
      ...tech,
      title: m.techTitle,
      subtitle: m.techSub(mainIng, title),
      stages: [
        {
          timeSeconds: 0,
          title: m.s1[0],
          cue: m.s1[1](mainIng, secondaryIng, aromatic),
          heatSetting: m.s1[2],
        },
        {
          timeSeconds: 5,
          title: m.s2[0],
          cue: m.s2[1](mainIng, secondaryIng, aromatic),
          heatSetting: m.s2[2],
        },
        {
          timeSeconds: 10,
          title: m.s3[0],
          cue: m.s3[1](secondaryIng, aromatic, finishing),
          heatSetting: m.s3[2],
        },
      ],
    })),
    steps: recipe.steps.map((step) => {
      if (step.stepNumber === 1) {
        return {
          ...step,
          title: storyT.step1Title(title),
          instruction: storyT.step1Text(mainIng, secondaryIng, aromatic),
          timerLabel: storyT.step1Timer,
          tip: m.tip,
        };
      }
      if (step.stepNumber === 2) {
        return {
          ...step,
          title: m.step2Title(mainIng, aromatic),
          instruction: m.step2Text(mainIng, secondaryIng, aromatic),
          timerLabel: m.step2Timer,
        };
      }
      if (step.stepNumber === 3) {
        return {
          ...step,
          title: m.step3Title(mainIng, secondaryIng, aromatic),
          instruction: m.step3Text(mainIng, secondaryIng, aromatic),
          timerLabel: m.step3Timer,
        };
      }
      return {
        ...step,
        title: m.step4Title(finishing),
        instruction: m.step4Text(finishing),
        timerLabel: m.step4Timer,
      };
    }),
  };
}
